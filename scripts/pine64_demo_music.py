#!/usr/bin/env python3
"""Create original FM+PSG exercise music for missing upstream VGM headers.

The score and generated VGM are dedicated to the public domain (CC0-1.0).
No game soundtrack or ROM data is used. Run from the repository root.
"""
import math
import struct
from pathlib import Path

clock = 7_670_454
commands = bytearray()
def fm(port, reg, value):
    commands.extend((0x52 + port, reg, value))
def psg(value):
    commands.extend((0x50, value))
def wait(samples):
    commands.append(0x61)
    commands.extend(struct.pack('<H', samples))
def freq(ch, note):
    hz = 440.0 * 2.0 ** ((note - 69) / 12.0)
    block = 4
    number = round(hz * 144 * 2 ** (21 - block) / clock)
    while number > 2047:
        block += 1
        number = (number + 1) // 2
    fm(ch // 3, 0xa4 + ch % 3, block << 3 | number >> 8)
    fm(ch // 3, 0xa0 + ch % 3, number & 255)
def on(ch):
    fm(0, 0x28, 0xf0 | (ch % 3) | (4 if ch >= 3 else 0))
def off(ch):
    fm(0, 0x28, (ch % 3) | (4 if ch >= 3 else 0))

fm(0, 0x22, 0)
fm(0, 0x27, 0)
fm(0, 0x2b, 0)
for channel in range(6):
    off(channel)
    for op in range(4):
        offset = channel % 3 + op * 4
        fm(channel // 3, 0x30 + offset, 1)
        fm(channel // 3, 0x40 + offset, 127 if op < 3 else 34 + channel * 3)
        fm(channel // 3, 0x50 + offset, 31)
        fm(channel // 3, 0x60 + offset, 8)
        fm(channel // 3, 0x70 + offset, 3)
        fm(channel // 3, 0x80 + offset, 0x48)
        fm(channel // 3, 0x90 + offset, 0)
    fm(channel // 3, 0xb0 + channel % 3, 7)
    fm(channel // 3, 0xb4 + channel % 3, 0xc0)
for channel in range(4):
    psg(0x90 | channel << 5 | 15)

# A 16-bar arpeggio exercise at120 BPM, with rotating six-channel FM
# voices and three PSG voices/noise. Loops include chip initialization.
total = 0
melody = [0, 7, 12, 4, 7, 16, 12, 7, 2, 9, 14, 5, 9, 17, 14, 9]
for step in range(128):
    root = [48, 45, 53, 55][(step // 16) % 4]
    channel = step % 6
    off(channel)
    freq(channel, root + 12 + melody[step % 16])
    on(channel)
    for tone in range(3):
        note = root + [0, 7, 12][tone]
        hz = 440.0 * 2.0 ** ((note - 69) / 12.0)
        period = max(1, min(1023, round(3_579_545 / (32 * hz))))
        psg(0x80 | tone << 5 | period & 15)
        psg(period >> 4)
        psg(0x90 | tone << 5 | [7, 11, 13][tone])
    psg(0xe4)  # periodic clocked noise/percussion
    psg(0xf5 if step % 4 == 0 else 0xfb)
    wait(8820)
    total += 8820
    off(channel)
    psg(0xff)
    wait(2205)
    total += 2205
commands.append(0x66)
header = bytearray(0x100)
header[:4] = b'Vgm '
for offset, value in {4: len(header) + len(commands) - 4,
                      8: 0x171, 0x0c: 3_579_545, 0x18: total,
                      0x1c: 0x100 - 0x1c, 0x20: total,
                      0x24: 60, 0x2c: clock, 0x34: 0x100 - 0x34}.items():
    struct.pack_into('<I', header, offset, value)
struct.pack_into('<H', header, 0x28, 9)
header[0x2a] = 16
blob = header + commands
out = Path('boards/pine64')
rows = [', '.join(f'0x{x:02x}' for x in blob[i:i+16]) for i in range(0, len(blob), 16)]
(out / 'demo_music.c').write_text(
    '/* Generated by scripts/pine64_demo_music.py; original score, CC0-1.0. */\n'
    '#include "demo_music.h"\nconst unsigned char pine64_demo_vgm[PINE64_DEMO_VGM_SIZE] = {\n    '
    + ',\n    '.join(rows) + '\n};\n')
(out / 'demo_music.h').write_text(
    '#ifndef PINE64_DEMO_MUSIC_H\n#define PINE64_DEMO_MUSIC_H\n'
    f'#define PINE64_DEMO_VGM_SIZE {len(blob)}u\n'
    'extern const unsigned char pine64_demo_vgm[PINE64_DEMO_VGM_SIZE];\n'
    '#define PINE64_MUSIC_TITLE "Jupiter FM+PSG exercise"\n'
    + ''.join(f'#undef vgm_{name}\n#undef vgm_{name}_len\n'
              f'#define vgm_{name} pine64_demo_vgm\n'
              f'#define vgm_{name}_len PINE64_DEMO_VGM_SIZE\n'
              for name in ('fighting_back', 'sortie', 'step_on_beat'))
    + '#endif\n')
print(f'Original demo VGM: {len(blob)} bytes, {total / 44100:.1f} seconds')
